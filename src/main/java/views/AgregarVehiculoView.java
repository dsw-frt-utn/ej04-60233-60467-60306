    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
            try {
            
            if (cmpPatente.getText().trim().isEmpty() || 
                cmpModelo.getText().trim().isEmpty() || 
                cmpMarca.getText().trim().isEmpty() ||
                cmpAnio.getText().trim().isEmpty() ||
                cmpCapCarga.getText().trim().isEmpty()) {
                
                javax.swing.JOptionPane.showMessageDialog(this, "Por favor, complete todos los campos obligatorios.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
                return;
            }

        
            String patente = cmpPatente.getText().trim().toUpperCase();
            String modelo = cmpModelo.getText().trim();
            String marcaNombre = cmpMarca.getText().trim();
            String pais=cmpPais.getText().trim();
            int anio = Integer.parseInt(cmpAnio.getText().trim());
            double capCarga = Double.parseDouble(cmpCapCarga.getText().trim());
            int indexSucursal = cmpSucursal.getSelectedIndex();
            
            String tipo = cmpTipoVehiculo.getSelectedItem().toString();
            boolean exito = false;

           
            if (tipo.equals("COMBUSTIBLE")) {
                if(cmpKmporlitros.getText().trim().isEmpty() || cmplitrosExtras.getText().trim().isEmpty()) {
                     javax.swing.JOptionPane.showMessageDialog(this, "Complete los campos específicos de Combustible.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
                     return;
                }
                double kmLitro = Double.parseDouble(cmpKmporlitros.getText().trim());
                double litrosExtra = Double.parseDouble(cmplitrosExtras.getText().trim());
                
                exito = Controlador.registrarVehiculoCombustible(patente, marcaNombre, modelo,pais, anio, capCarga, indexSucursal, kmLitro, litrosExtra);
            } else {
                if(cmpKwhBase.getText().trim().isEmpty()) {
                     javax.swing.JOptionPane.showMessageDialog(this, "Complete el campo Kwh Base.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
                     return;
                }
                double kwhBase = Double.parseDouble(cmpKwhBase.getText().trim());
                
                exito = Controlador.registrarVehiculoElectrico(patente, marcaNombre, modelo,pais, anio, capCarga, indexSucursal, kwhBase);
            }

            
            if (exito) {
                javax.swing.JOptionPane.showMessageDialog(this, "Vehículo registrado exitosamente.");
                actualizarTabla();
                limpiarCampos();
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Error: Ya existe un vehículo con esa patente.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            }

        } catch (NumberFormatException e) {
           
            javax.swing.JOptionPane.showMessageDialog(this, "Error de formato: Asegúrese de ingresar números válidos en Año, Capacidad y Consumos.", "Datos inválidos", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
            
           
    }//GEN-LAST:event_btnRegistrarActionPerformed

