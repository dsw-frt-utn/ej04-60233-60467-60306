    private void configurarEventosYVista() {
        
        cmpTipoVehiculo.addActionListener(evt -> {
            boolean esCombustible = cmpTipoVehiculo.getSelectedItem().toString().equals("COMBUSTIBLE");
            
            // Campos de Combustible
            cmpKmporlitros.setVisible(esCombustible);
            cmplitrosExtras.setVisible(esCombustible);
            jLabel7.setVisible(esCombustible);
            jLabel8.setVisible(esCombustible);
            
            
            cmpKwhBase.setVisible(!esCombustible); 
            jLabel10.setVisible(!esCombustible);
            
            
            this.revalidate();
            this.repaint();
        });
        
        cmpTipoVehiculo.setSelectedIndex(0); 

        
        btnEliminar.addActionListener(this::btnEliminarActionPerformed);
    }

    
    private void actualizarTabla() {
        javax.swing.table.DefaultTableModel modelo = new javax.swing.table.DefaultTableModel(
            new Object[][] {},
            new String[] {"Patente", "Marca-Modelo-Pais", "Sucursal"}
        ) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false; 
            }
        };
        
        for (VehiculoViewModel v : Controlador.getVehiculos()) {
            modelo.addRow(new Object[]{
                v.getPatente(),
                v.getVehiculo(),
                v.getSucursal()
            });
        }
        jTable1.setModel(modelo);
    }

